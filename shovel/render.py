def render_csv(registry_payload: dict, path: Path) -> Path:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=CSV_FIELDS, extrasaction="ignore")
    writer.writeheader()
    for resource in registry_payload.get("resources", []):
        row = dict(resource)
        row["tags"] = ";".join(row.get("tags") or [])
        row["status"] = row.get("status") or "unknown"
        writer.writerow(row)
    util.atomic_write(path, buffer.getvalue())
    return path


def render_feed(changes: list[dict], path: Path) -> Path:
    items = []
    for change in (changes or [])[-50:][::-1]:
        items.append(
            "<item>"
            f"<title>{xml_escape(str(change.get('name') or change.get('source') or '变更'))} "
            f"+{change.get('added_count', 0)} / -{change.get('removed_count', 0)}</title>"
            f"<link>{xml_escape(_panel_url())}</link>"
            f"<guid isPermaLink=\"false\">{xml_escape(str(change.get('at') or ''))}</guid>"
            f"<pubDate>{_rfc822(change.get('at'))}</pubDate>"
            f"<description>{xml_escape(_change_text(change))}</description>"
            "</item>"
        )
    content = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<rss version="2.0"><channel>'
        "<title>每日免费算力资源清单 — 变更</title>"
        f"<link>{xml_escape(_panel_url())}</link>"
        "<description>新增、移除与状态变化</description>"
        "<language>zh-cn</language>"
        + "".join(items)
        + "</channel></rss>\n"
    )
    util.atomic_write(path, content)
    return path


def _change_text(change: dict) -> str:
    parts = []
    added = change.get("added") or []
    removed = change.get("removed") or []
    if added:
        parts.append("新增: " + "; ".join(str(item).split(" | ")[1] if " | " in str(item) else str(item) for item in added[:10]))
    if removed:
        parts.append("移除: " + "; ".join(str(item).split(" | ")[1] if " | " in str(item) else str(item) for item in removed[:10]))
    return " / ".join(parts)


def _rfc822(value) -> str:
    try:
        moment = datetime.strptime(str(value), "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    except (TypeError, ValueError):
        moment = datetime.now(timezone.utc)
    return format_datetime(moment)


