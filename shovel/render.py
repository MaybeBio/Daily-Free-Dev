GENERATED_MARKER = "<!-- generated by shovel: edit config/resources.json, then run `python -m shovel report` -->"


def _panel_url() -> str:
    repo = os.environ.get("GITHUB_REPOSITORY", "")
    if "/" in repo:
        owner, name = repo.split("/", 1)
        return f"https://{owner.lower()}.github.io/{name}/"
    return "site/index.html"


def _feed_url() -> str:
    panel = _panel_url()
    return f"{panel}feed.xml" if panel.startswith("http") else "site/feed.xml"


